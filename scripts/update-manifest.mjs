// Rebuild clips.json and slides.js from assets/clips and assets/themes/<name>/.
// Run: node scripts/update-manifest.mjs
// Check only: node scripts/update-manifest.mjs --check

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLIP_DIR = path.join(ROOT, 'assets', 'clips');
const THEME_DIR = path.join(ROOT, 'assets', 'themes');
const MEDIA = /\.(mp4|webm|mov|m4v|jpe?g|png|gif|webp)$/i;
const KNOWN = ['halloween', 'boiler', 'thanksgiving', 'christmas', 'newyear', 'valentines', 'stpatricks', 'july4', 'shop'];

function listMedia(dir, urlPrefix) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter(name => MEDIA.test(name) && fs.statSync(path.join(dir, name)).isFile())
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }))
    .map(file => {
      const full = path.join(dir, file);
      const bytes = fs.statSync(full).size;
      const hash = createHash('sha1').update(fs.readFileSync(full)).digest('hex').slice(0, 10);
      return { file, src: `${urlPrefix}/${file}?v=${hash}`, bytes };
    });
}

function themes() {
  const found = {};
  KNOWN.forEach(id => { found[id] = []; });
  found.halloween = listMedia(CLIP_DIR, 'assets/clips').concat(listMedia(path.join(THEME_DIR, 'halloween'), 'assets/themes/halloween'));
  found.halloween.sort((a, b) => a.file.localeCompare(b.file, undefined, { numeric: true, sensitivity: 'base' }));

  if (fs.existsSync(THEME_DIR)) {
    fs.readdirSync(THEME_DIR).forEach(name => {
      const dir = path.join(THEME_DIR, name);
      if (!fs.statSync(dir).isDirectory()) return;
      if (name === 'halloween') return;
      const clips = listMedia(dir, `assets/themes/${name}`);
      found[name] = (found[name] || []).concat(clips);
    });
  }
  return found;
}

function slidesJs(groups) {
  const body = Object.keys(groups).map(id => {
    if (!groups[id].length) return `  ${JSON.stringify(id)}: []`;
    const lines = groups[id].map(clip => `    ${JSON.stringify(clip.src)}`);
    return `  ${JSON.stringify(id)}: [\n${lines.join(',\n')}\n  ]`;
  }).join(',\n');
  return [
    '// Generated by scripts/update-manifest.mjs. Do not edit by hand.',
    'window.SLIDES = {',
    body,
    '};',
    ''
  ].join('\n');
}

function clipsJson(groups) {
  return JSON.stringify({ themes: groups }, null, 2) + '\n';
}

function playlistHash(groups) {
  const flat = [];
  Object.keys(groups).forEach(id => groups[id].forEach(clip => flat.push(id + ':' + clip.src)));
  return createHash('sha1').update(flat.join('\n')).digest('hex').slice(0, 8);
}

function htmlWithHash(html, hash) {
  const re = /(<script\s+src="slides\.js\?v=)[^"]+(")/;
  if (!re.test(html)) {
    throw new Error('index.html is missing the slides.js?v= cache-busting query');
  }
  return html.replace(re, `$1${hash}$2`);
}

function read(rel) {
  const full = path.join(ROOT, rel);
  return fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : '';
}

function write(rel, text) {
  fs.writeFileSync(path.join(ROOT, rel), text);
}

const groups = themes();
const halloweenCount = groups.halloween.length;
if (!halloweenCount) {
  console.error('No Halloween media in assets/clips or assets/themes/halloween.');
  process.exit(1);
}

const json = clipsJson(groups);
const js = slidesJs(groups);
const hash = playlistHash(groups);
const html = htmlWithHash(read('index.html'), hash);
const check = process.argv.includes('--check');
const current = { json: read('clips.json'), js: read('slides.js'), html: read('index.html') };
const changed = [];
if (current.json !== json) changed.push('clips.json');
if (current.js !== js) changed.push('slides.js');
if (current.html !== html) changed.push('index.html');

if (check) {
  if (changed.length) {
    console.error('Playlist is out of date: ' + changed.join(', '));
    console.error('Run: node scripts/update-manifest.mjs');
    process.exit(1);
  }
  console.log(`Playlist is up to date (${halloweenCount} Halloween clips).`);
  process.exit(0);
}

if (!changed.length) {
  console.log(`Playlist already matches the theme folders (${halloweenCount} Halloween clips).`);
  process.exit(0);
}

if (changed.includes('clips.json')) write('clips.json', json);
if (changed.includes('slides.js')) write('slides.js', js);
if (changed.includes('index.html')) write('index.html', html);
console.log('Updated ' + changed.join(', ') + ` (${halloweenCount} Halloween clips).`);
