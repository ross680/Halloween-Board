// Rebuild clips.json and slides.js from assets/clips.
// Run: node scripts/update-manifest.mjs
// Check only (exit 1 if a commit would change the playlist): node scripts/update-manifest.mjs --check

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLIP_DIR = path.join(ROOT, 'assets', 'clips');
const MEDIA = /\.(mp4|webm|mov|m4v|jpe?g|png|gif|webp)$/i;

function playlist() {
  const names = fs.readdirSync(CLIP_DIR)
    .filter(name => MEDIA.test(name) && fs.statSync(path.join(CLIP_DIR, name)).isFile())
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

  const clips = names.map(file => {
    const full = path.join(CLIP_DIR, file);
    const bytes = fs.statSync(full).size;
    const hash = createHash('sha1').update(fs.readFileSync(full)).digest('hex').slice(0, 10);
    return {
      file,
      src: `assets/clips/${file}?v=${hash}`,
      bytes
    };
  });
  return clips;
}

function slidesJs(clips) {
  const lines = clips.map(clip => `  ${JSON.stringify(clip.src)}`);
  return [
    '// Generated by scripts/update-manifest.mjs. Do not edit by hand.',
    'window.SLIDES = [',
    lines.join(',\n'),
    '];',
    ''
  ].join('\n');
}

function clipsJson(clips) {
  return JSON.stringify({ clips }, null, 2) + '\n';
}

function playlistHash(clips) {
  return createHash('sha1').update(clips.map(c => c.src).join('\n')).digest('hex').slice(0, 8);
}

function htmlWithHash(html, hash) {
  const re = /(<script\s+src="slides\.js\?v=)[^"]+(")/;
  if (!re.test(html)) {
    throw new Error('index.html is missing the slides.js?v= cache-busting query');
  }
  return html.replace(re, `$1${hash}$2`);
}

function read(rel) {
  const full = path.join(ROOT, rel);
  return fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : '';
}

function write(rel, text) {
  fs.writeFileSync(path.join(ROOT, rel), text);
}

const clips = playlist();
if (!clips.length) {
  console.error('No media files in assets/clips.');
  process.exit(1);
}

const json = clipsJson(clips);
const js = slidesJs(clips);
const hash = playlistHash(clips);
const html = htmlWithHash(read('index.html'), hash);
const check = process.argv.includes('--check');

const current = {
  json: read('clips.json'),
  js: read('slides.js'),
  html: read('index.html')
};

const changed = [];
if (current.json !== json) changed.push('clips.json');
if (current.js !== js) changed.push('slides.js');
if (current.html !== html) changed.push('index.html');

if (check) {
  if (changed.length) {
    console.error('Playlist is out of date: ' + changed.join(', '));
    console.error('Run: node scripts/update-manifest.mjs');
    process.exit(1);
  }
  console.log(`Playlist is up to date (${clips.length} clips).`);
  process.exit(0);
}

if (!changed.length) {
  console.log(`Playlist already matches assets/clips (${clips.length} clips).`);
  process.exit(0);
}

if (changed.includes('clips.json')) write('clips.json', json);
if (changed.includes('slides.js')) write('slides.js', js);
if (changed.includes('index.html')) write('index.html', html);
console.log('Updated ' + changed.join(', ') + ` (${clips.length} clips).`);
