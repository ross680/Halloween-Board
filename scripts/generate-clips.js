#!/usr/bin/env node
'use strict';
// Rebuild clips.json and slides.js from the media files in assets/clips.
// Run locally or from .github/workflows/update-clips.yml. Do not hand-edit
// the files this writes; the next run replaces them.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const clipsDir = path.join(root, 'assets', 'clips');
const manifestPath = path.join(root, 'clips.json');
const slidesPath = path.join(root, 'slides.js');
// Keep in sync with the media test in app.js.
const MEDIA = /\.(mp4|webm|mov|m4v|jpe?g|png|gif|webp)$/i;

function byName(a, b) {
  return a.localeCompare(b, undefined, { numeric: true });
}

const slides = fs.readdirSync(clipsDir, { withFileTypes: true })
  .filter(entry => entry.isFile() && MEDIA.test(entry.name))
  .map(entry => 'assets/clips/' + entry.name)
  .sort(byName);

let generated = new Date().toISOString();
try {
  const previous = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const previousSlides = Array.isArray(previous.slides) ? previous.slides : [];
  if (typeof previous.generated === 'string' && JSON.stringify(previousSlides) === JSON.stringify(slides)) {
    generated = previous.generated;
  }
} catch (e) {}

const manifest = JSON.stringify({ generated, slides }, null, 2) + '\n';
const slidesJs = [
  '// Generated by scripts/generate-clips.js. Do not edit by hand.',
  'window.SLIDES = ' + JSON.stringify(slides, null, 2) + ';',
  '',
].join('\n');

fs.writeFileSync(manifestPath, manifest);
fs.writeFileSync(slidesPath, slidesJs);
console.log('Wrote ' + slides.length + ' clip' + (slides.length === 1 ? '' : 's') + ' to clips.json and slides.js');
slides.forEach(name => console.log('  ' + name));
